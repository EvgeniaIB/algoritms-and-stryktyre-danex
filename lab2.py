def task10(year):
    """10. Название года по восточному календарю (1984 - год зеленой крысы)."""
    animals = ["крысы", "коровы", "тигра", "зайца", "дракона", "змеи", 
               "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи"]
    colors = ["зеленой", "красной", "желтой", "белой", "черной"]
    
    
    diff = year - 1984
    
    
    animal_idx = diff % 12
    
    
    color_idx = (diff // 12) % 5
    
    return f"год {colors[color_idx]} {animals[animal_idx]}"


