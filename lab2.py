import math

def task1(a, b):
    """1. Если A != B, присвоить обоим большее. Если равны — нули."""
    if a != b:
        max_val = max(a, b)
        return max_val, max_val
    else:
        return 0, 0

def task2(a, b, c):
    """2. Сумма двух наибольших из трех чисел."""
    
    numbers = sorted([a, b, c])
    return numbers[-1] + numbers[-2]

def task3(xa, ya, xb, yb, xc, yc):
    """3. Какая из точек B или C ближе к A, и расстояние до неё."""
    dist_b = math.sqrt((xb - xa)**2 + (yb - ya)**2)
    dist_c = math.sqrt((xc - xa)**2 + (yc - ya)**2)
    
    if dist_b < dist_c:
        return "B", dist_b
    elif dist_c < dist_b:
        return "C", dist_c
    else:
        return "Одинаково", dist_b

def task4(x, y):
    """4. Номер координатной четверти (точка не на осях)."""
    if x > 0 and y > 0:
        return 1
    elif x < 0 and y > 0:
        return 2
    elif x < 0 and y < 0:
        return 3
    elif x > 0 and y < 0:
        return 4
    else:
        return "Точка лежит на оси!"

def task5(num):
    """5. Строка-описание целого числа (знак и четность)."""
    if num == 0:
        return "нулевое число"
    
    sign = "положительное" if num > 0 else "отрицательное"
    parity = "четное" if num % 2 == 0 else "нечетное"
    
    return f"{sign} {parity} число"

def task6(num):
    """6. Описание числа от 1 до 999 (четность и разрядность)."""
    if not (1 <= num <= 999):
        return "Число вне диапазона 1-999"
        
    parity = "четное" if num % 2 == 0 else "нечетное"
    
    if 1 <= num <= 9:
        digits = "однозначное"
    elif 10 <= num <= 99:
        digits = "двузначное"
    else:
        digits = "трехзначное"
        
    return f"{parity} {digits} число"

