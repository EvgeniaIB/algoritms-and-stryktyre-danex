import queue
from collections import deque

def demo_queue_module():
    """Демонстрация работы с модулем queue (потокобезопасная очередь)"""

    print("1. МОДУЛЬ queue (для многопоточных задач)")

    
    # 1. Создание очереди
    q = queue.Queue()
    print("Создана пустая очередь.")
    
    # 2. Добавление элементов
    print("\nДобавляем элементы 10, 20, 30...")
    q.put(10)
    q.put(20)
    q.put(30)
    
    # 3. Проверка размера
    print(f"Размер очереди: {q.qsize()}")
    
    # 4. Проверка пустоты
    print(f"Очередь пуста? {q.empty()}")
    
    # 5. Проверка наличия элемента (заглядываем внутрь)
    print(f"Есть ли 20 в очереди? {20 in q.queue}")
    
    # 6. Получение элемента (извлекаем)
    item = q.get()
    print(f"\nИзвлечен элемент: {item}")
    print(f"Новый размер очереди: {q.qsize()}")
    
    # 7. Перебор элементов (без удаления)
    print("Оставшиеся элементы в очереди:")
    for el in q.queue:
        print(f"  - {el}")
        
    # 8. Очистка
    q.queue.clear()
    print(f"\nПосле очистки очередь пуста? {q.empty()}")


def demo_deque():
    """Демонстрация работы с collections.deque (быстрая очередь)"""

    print("2. МОДУЛЬ collections.deque (для быстрого доступа)")

    
    # 1. Создание пустой очереди
    q = deque()
    
    # 2. Добавление элементов (в конец)
    print("Добавляем 1, 2, 3 в очередь...")
    q.append(1)
    q.append(2)
    q.append(3)
    
    # 3. Получение элемента из начала (FIFO)
    item = q.popleft()
    print(f"Извлечен элемент из начала: {item}")
    
    # 4. Просмотр первого элемента (без удаления)
    print(f"Текущий первый элемент: {q[0]}")
    
    # 5. Проверка пустоты через длину
    print(f"Очередь пуста? {len(q) == 0}")
    
    # 6. Получение размера
    print(f"Текущий размер очереди: {len(q)}")
    
    # 7. Перебор элементов
    print("Элементы в очереди:")
    for el in q:
        print(f"  - {el}")


if __name__ == "__main__":
    demo_queue_module()
    demo_deque()

    print("Работа с очередью успешно завершена!")
  